"""Fictional outcome generation and retrospective evaluation, never selection.

Do not expose truth.csv to the proposer or use it for tuning seeds/model settings.
"""
import math
import random

from contract import (COLUMNS, IDENTITY, OUTCOMES, catalog, csv_bytes, encoded,
                      load_state, number, publish, read_csv, records, require,
                      verify_bundle)

TRUTH = ['target_id', 'latent_value', 'measured_value']


def generate(out, seed=17, count=200):
    require(type(count) is int and 100 <= count <= 1000, 'Count must be 100..1000')
    require(type(seed) is int and 0 <= seed <= 2**32-1, 'Invalid seed')
    rng = random.Random(seed)
    candidates, truth = [], []
    for i in range(count):
        target = f'FABLE-{i:04}'
        x, y = rng.uniform(-1, 1), rng.uniform(-1, 1)
        status = 'excluded' if i == 0 else 'invalid' if i == 1 else 'valid'
        candidates.append(dict(target_id=target, f1=x, f2=y, status=status))
        # An arbitrary smooth toy surface, unrelated to any biological entity.
        latent = 1.2 * math.exp(-((x-.3)**2 + (y+.2)**2)/.22) + .25*math.sin(3*x)*math.cos(2*y)
        truth.append(dict(target_id=target, latent_value=latent, measured_value=latent+rng.gauss(0, .1)))
    initial_ids = random.Random(seed).sample(list(range(2, count)), 6)
    initial = [dict(target_id=truth[i]['target_id'], sample_id=f'S-init-{i:04}', round_id='r000',
                    outcome_id=f'O-init-{i:04}', value=truth[i]['measured_value']) for i in initial_ids]
    publish(out, {'candidates.csv': csv_bytes(COLUMNS, candidates),
                  'truth.csv': csv_bytes(TRUTH, truth),
                  'initial-outcomes.csv': csv_bytes(OUTCOMES, initial),
                  'simulation.json': encoded({'fictional': True, 'seed': seed, 'count': count,
                                              'noise_std': .1, 'initial_n': 6})})


def read_truth(path, candidates):
    rows = read_csv(path, TRUTH)
    require(len(rows) == len(candidates) and {r['target_id'] for r in rows} == {r['target_id'] for r in candidates}, 'Truth targets mismatch/duplicate')
    return {r['target_id']: {k: number(r[k]) for k in ('latent_value', 'measured_value')} for r in rows}


def measure(state_path, truth_path, out):
    state = load_state(state_path)
    require(state['pending'], 'No pending simulated measurements')
    truth = read_truth(truth_path, state['candidates'])
    rows = [{**r, 'value': truth[r['target_id']]['measured_value']} for r in state['pending']]
    publish(out, {'outcomes.csv': csv_bytes(OUTCOMES, rows)}, (state_path, truth_path))


def evaluate(adaptive_path, random_path, truth_path, out):
    adaptive, baseline = load_state(adaptive_path), load_state(random_path)
    require(not adaptive['pending'] and not baseline['pending'], 'Cannot evaluate pending outcomes')
    require(adaptive['seed'] == baseline['seed'] and adaptive['candidates'] == baseline['candidates'], 'Comparison inputs differ')
    a0 = [r for r in adaptive['observed'] if r['round_id'] == 'r000']
    b0 = [r for r in baseline['observed'] if r['round_id'] == 'r000']
    require(a0 == b0, 'Initial observations differ')
    require(len(adaptive['observed']) == len(baseline['observed']), 'Unequal evaluation budget')
    require([sum(r['round_id'] == f'r{i:03}' for r in adaptive['observed']) for i in range(4)] ==
            [sum(r['round_id'] == f'r{i:03}' for r in baseline['observed']) for i in range(4)], 'Unequal batch budgets')
    # Require the recorded branch strategies, rather than merely trusting CLI labels.
    for path, strategy in ((adaptive_path, 'adaptive'), (random_path, 'random')):
        from pathlib import Path
        import json
        cursor = Path(path).resolve()
        while True:
            state = load_state(cursor)
            if state['event'] == 'propose':
                require(json.loads((cursor / 'fit.json').read_text())['strategy'] == strategy, 'Strategy mismatch')
            if state['parent'] is None:
                break
            cursor = (cursor / state['parent']['path']).resolve()
    truth = read_truth(truth_path, adaptive['candidates'])
    eligible = {r['target_id'] for r in adaptive['candidates'] if r['status'] == 'valid'}
    optimum = max(truth[t]['latent_value'] for t in eligible)
    results = {}
    for name, state in [('adaptive', adaptive), ('random', baseline)]:
        trajectory = []
        for round_id in range(state['round']+1):
            measured = [r for r in state['observed'] if r['round_id'] <= f'r{round_id:03}']
            # This evaluator accepts only outcomes actually generated by this toy oracle.
            require(all(r['value'] == truth[r['target_id']]['measured_value'] for r in measured), 'Ledger differs from simulated measurements')
            best_latent = max(truth[r['target_id']]['latent_value'] for r in measured)
            trajectory.append(dict(round=round_id, n=len(measured), observed_best=max(r['value'] for r in measured),
                                   hidden_best_measured_target=best_latent, hidden_simple_regret=optimum-best_latent))
        results[name] = trajectory
    publish(out, {'comparison.json': encoded({'fictional': True, 'seed': adaptive['seed'],
        'hidden_eligible_optimum': optimum, 'equal_budget': len(adaptive['observed']),
        'trajectories': results, 'superiority_required': False})}, (adaptive_path, random_path, truth_path))
